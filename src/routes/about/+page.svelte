<div class="narrower position-relative start-50 translate-middle-x">
  <h1 style="margin-top: 10%;">
    <i class="bi bi-info-circle page-icon" />
    About IdentitySign
  </h1>

  <p class="main-text">
    IdentitySign is a free and open-source application for creating, verifying
    and requesting signatures on PDF documents. It aims to be easy to use and is
    available to everyone that wants or needs to work with signatures on PDF
    documents.
  </p>

  <h2 class="prototype-warning">Prototype</h2>

  <p class="main-text prototype-warning">
    Please note that this application is only a prototype and does not actually
    sign files using a proper signature. It is meant solely for testing and
    research purposes.<br />
    <b>Do NOT use this application for actually signing documents!</b>
  </p>

  <h2>Functionality</h2>

  <div class="main-text">
    IdentitySign provides the following functionality:
    <ol>
      <li>Signing documents</li>
      <p class="li-p">
        Use IdentitySign to create a signature on documents based on your
        personal data.
      </p>
      <li>Verifying signatures</li>
      <p class="li-p">
        Verify that signatures made using IdentitySign are valid and see what
        personal data was used to make them.
      </p>
      <li>Requesting signatures from others</li>
      <p class="li-p">
        Request that others sign a document using IdentitySign.
      </p>
    </ol>
  </div>

  <h2>Privacy</h2>

  <p class="main-text">
    Because IdentitySign runs completely on your own device and never sends the
    documents you work with to another device or service, you can rest assured
    that your documents stay private! But you don't have to trust us on this
    either; This application is open-source and anyone can verify how it works
    and what it does to your data.
  </p>

  <h2>Ease of use</h2>

  <p class="main-text">
    No need to create another account or do complex key management! All you need
    is your identity wallet containing the attributes you want to sign your
    documents with.
  </p>

  <h2>Free! In every sense of the word</h2>

  <p class="main-text">
    No subscriptions or any other payments needed! Anyone can use this
    application for free, contibute improvements or grab the source code and
    create their own version!
  </p>

  <h2>Got any questions?</h2>

  <p class="main-text">
    Check out our <a href="/faq">frequently asked questions</a>, we might have
    already answered them for you!
  </p>

