  <h1 style="margin-top: 20px;">Frequently asked questions</h1>

  <h3>
    <i class="bi bi-caret-right-fill"></i>
    What is a digital signature and why would I use one to sign a document?
  </h3>

  <p class="main-text">
    Digital signatures use mathematics to create a signature that can be used to
    verify who signed something (authenticity) and that nothing was changed
    since the signature was made (integrity). This can be very useful in a lot
    of situations, for example when signing contracts or issuing certificates!
  </p>

  <h3>
    <i class="bi bi-caret-right-fill"></i>
    What types of documents does IdentitySign work with?
  </h3>

  <p class="main-text">
    For now, IdentitySign only works with PDF documents. Most (if not all) word
    processors (like Microsoft Word or Libreoffice) support exporting documents
    in this file format.
  </p>

  <h3>
    <i class="bi bi-caret-right-fill"></i>
    How is IdentitySign different from other signature providers?
  </h3>

  <p class="main-text">
    IdentitySign does not upload your documents to an external server to sign
    them. Documents always stay on your own device! This allows you to sign
    sensitive documents without having to send them (and the information on
    them) to a third party. Besides not uploading your documents, IdentitySign
    is also completely free! No subscriptions or other payment is required to
    use any of IdentitySign's features!
  </p>

  <h3>
    <i class="bi bi-caret-right-fill"></i>
    Why does the file selection window say "Upload file" (or something similar) when
    none of my information should be shared?
  </h3>

  <p class="main-text">
    This is due to your browser assigning this text to this window. Even though
    no information whatsoever is sent to another device or service, this text
    will always remain the same. If you want, you can look at our source code to
    verify this!
  </p>
